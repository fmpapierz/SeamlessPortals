    @Test
    void cameraRotationMapsViewDirectionToNegativeZ() {
        // Analytically getCameraRotation(0,0) = Ry(180°): pitch term is identity and the yaw
        // term rotates 0+180 about ŷ. MC yaw 0 = facing +Z (south); the world-to-camera
        // rotation must map the view direction to OpenGL camera-forward -ẑ (Ry180: ẑ→-ẑ).
        DQuaternion q = DQuaternion.getCameraRotation(0, 0);
        assertVec(new Vec3(0, 0, -1), q.rotate(new Vec3(0, 0, 1)), EPS,
            "yaw 0 view direction (+Z) maps to camera -Z");
        // Closed form at (0,0): p=y=0 → (-sin0 sin0, cos0 cos0, sin0 cos0, -cos0 sin0) = (0,1,0,0).
        assertQuatComponents(0, 1, 0, 0, DQuaternion.getCameraRotation1(0, 0), EPS,
            "closed form at pitch=yaw=0 is the pure Ry(180°) quaternion");
    }

    @Test
    void cameraRotationClosedFormAgreesWithComposition() {
        // Hand-derivation that the two must agree (port-note S02-qmiscutil.md §4.3):
        // Rx(pitch) ⊗ Ry(yaw+180) with r2 = (0, cos y, 0, -sin y) (half-angle shift by 90°)
        // expands to exactly (-sin p sin y, cos p cos y, sin p cos y, -cos p sin y)
        // = getCameraRotation1. Verified here over a pitch×yaw grid including the poles.
        double[] pitches = {-90, -30, 0, 45.5, 90};
        double[] yaws = {-180, -77.7, 0, 30.25, 90, 179, 270};
        for (double pitch : pitches) {
            for (double yaw : yaws) {
                assertSameRotation(
                    DQuaternion.getCameraRotation(pitch, yaw),
                    DQuaternion.getCameraRotation1(pitch, yaw),
                    EPS,
                    "getCameraRotation vs closed form at pitch=" + pitch + " yaw=" + yaw
                );
            }
        }
    }

    @Test
    void pitchYawRoundTrip() {
        // Analytic inverse (hand-verified): with p=rad(pitch)/2, y=rad(yaw)/2 the closed-form
        // components give 2(Y²+Z²)-1 = cos(yaw), -2(XZ+YW) = sin(yaw),
        // 1-2(X²+Z²) = cos(pitch), 2(XW+YZ) = sin(pitch) — so atan2 recovers both exactly.
        double[][] cases = {{30, 45}, {-60, -120}, {0, 179}, {89, -179}};
        for (double[] c : cases) {
            DQuaternion q = DQuaternion.getCameraRotation1(c[0], c[1]);
            Pair<Double, Double> pitchYaw = DQuaternion.getPitchYawFromRotation(q);
            assertEquals(c[0], pitchYaw.getFirst(), 1e-9, "pitch recovered for " + c[0] + "/" + c[1]);
            assertEquals(c[1], pitchYaw.getSecond(), 1e-9, "yaw recovered for " + c[0] + "/" + c[1]);
        }
    }

    // ------------------------------------------------------------------------- interpolation

    @Test
    void interpolateSlerpHalfwayBetweenSameAxisRotationsHalvesTheAngle() {
        // slerp(identity, Ry(90°), 0.5) = Ry(45°) = (0, sin22.5°, 0, cos22.5°).
        // dot = cos45° ≈ 0.707 < 0.9995, so this exercises the true slerp branch.
        DQuaternion a = DQuaternion.identity;
        DQuaternion b = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90);
        DQuaternion mid = DQuaternion.interpolate(a, b, 0.5);
        assertQuatComponents(0, SIN22_5, 0, COS22_5, mid, EPS, "slerp midpoint = Ry(45°)");

        // Endpoints reproduce the inputs (s0=1,s1=0 at t=0; s0=0,s1=1 at t=1).
        assertQuatComponents(a.x, a.y, a.z, a.w, DQuaternion.interpolate(a, b, 0), EPS, "t=0 is a");
        assertQuatComponents(b.x, b.y, b.z, b.w, DQuaternion.interpolate(a, b, 1), EPS, "t=1 is b");
    }

    @Test
    void interpolateNlerpBranchForCloseInputs() {
        // dot = cos(0.5°) ≈ 0.99996 > 0.9995 → the nlerp fast path. For the exact midpoint of
        // two unit quaternions on the same great circle, normalize(a+b) IS the true midpoint:
        // Ry(0.5°) = (0, sin0.25°, 0, cos0.25°).
        DQuaternion a = DQuaternion.identity;
        DQuaternion b = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 1);
        DQuaternion mid = DQuaternion.interpolate(a, b, 0.5);
        assertQuatComponents(
            0, Math.sin(Math.toRadians(0.25)), 0, Math.cos(Math.toRadians(0.25)),
            mid, EPS, "nlerp midpoint = Ry(0.5°)"
        );
    }

    @Test
    void interpolateHandlesDoubleCover() {
        // b and -b are the same rotation; interpolate must flip the sign (dot < 0 branch)
        // and still land on the Ry(45°) rotation at t=0.5.
        DQuaternion a = DQuaternion.identity;
        DQuaternion bNegated = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90).multiply(-1);
        DQuaternion mid = DQuaternion.interpolate(a, bNegated, 0.5);
        assertSameRotation(
            new DQuaternion(0, SIN22_5, 0, COS22_5), mid, EPS,
            "midpoint through the antipodal representative is still Ry(45°)"
        );
    }

