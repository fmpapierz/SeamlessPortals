    @Test
    void fixFloatingPointErrorAccumulationSnapsNearAxisValues() {
        // All four components are within the 1e-7 snap threshold of {0, 1}:
        // (1e-9, -1e-8, 5e-9, 1+3e-8) → (0, 0, 0, 1), then normalization keeps it exact.
        DQuaternion drifted = new DQuaternion(1e-9, -1e-8, 5e-9, 1 + 3e-8);
        DQuaternion fixed = drifted.fixFloatingPointErrorAccumulation();
        assertQuatComponents(0, 0, 0, 1, fixed, 0, "drifted identity snaps to exact identity");

        // A rotation whose components are far from {0,±1} must pass through unchanged
        // (up to re-normalization): 90° about Y has components ±sin45°.
        DQuaternion ry90 = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90);
        DQuaternion fixedRy90 = ry90.fixFloatingPointErrorAccumulation();
        assertQuatComponents(0, SIN45, 0, SIN45, fixedRy90, 1e-15, "non-near values unchanged");
    }

    @Test
    void isAxisAlignedChecksExactComponents() {
        assertTrue(DQuaternion.identity.isAxisAligned(), "identity is axis-aligned");
        assertTrue(new DQuaternion(1, 0, 0, 0).isAxisAligned(), "180° about X is axis-aligned");
        assertTrue(new DQuaternion(0, 0, 0, -1).isAxisAligned(), "negative identity is axis-aligned");
        assertFalse(DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90).isAxisAligned(),
            "sin45° components are not axis-aligned");
    }

    // ------------------------------------------------------------------- distance / closeness

    @Test
    void distanceSqAndIsCloseHandleDoubleCover() {
        DQuaternion q = DQuaternion.rotationByDegrees(new Vec3(1, 2, 3), 73);
        assertEquals(0, DQuaternion.distanceSq(q, q.multiply(-1)), 0,
            "q and -q are the same rotation → distance 0");
        assertTrue(DQuaternion.isClose(q, q.multiply(-1)), "isClose across the double cover");

        // Hand value: distanceSq(identity, Ry90) = min(v1, v2) with
        // v1 = (sin45)² + (1-cos45)² = 2 - 2cos45° = 2 - sqrt(2); v2 = 2 + sqrt(2) → 2 - sqrt(2).
        DQuaternion ry90 = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90);
        assertEquals(2 - Math.sqrt(2), DQuaternion.distanceSq(DQuaternion.identity, ry90), EPS,
            "hand-computed distanceSq");
        assertFalse(DQuaternion.isClose(DQuaternion.identity, ry90),
            "distinct rotations are not close");
    }

    // ------------------------------------------------------------------------- euler bridge

    @Test
    void eulerAngleAxisConventions() {
        // IP convention (ported bit-for-bit, port-note S02-qmiscutil.md §4.3): fromEulerAngle applies
        // rotZ(roll) · rotY(-yaw) · rotX(pitch) — note the NEGATED yaw (MC yaw is
        // left-handed about +Y). Float path → EPS_F.
        // pitch 90: rotX(90°) maps ŷ→ẑ.
        assertVec(new Vec3(0, 0, 1),
            DQuaternion.fromEulerAngle(new Vec3(90, 0, 0)).rotate(new Vec3(0, 1, 0)), EPS_F,
            "pitch is right-handed about +X");
        // yaw 90 → rotY(-90°) maps x̂→ẑ (right-handed +90° about Y would map x̂→-ẑ).
        assertVec(new Vec3(0, 0, 1),
            DQuaternion.fromEulerAngle(new Vec3(0, 90, 0)).rotate(new Vec3(1, 0, 0)), EPS_F,
            "yaw is NEGATED (left-handed about +Y)");
        // roll 90: rotZ(90°) maps x̂→ŷ.
        assertVec(new Vec3(0, 1, 0),
            DQuaternion.fromEulerAngle(new Vec3(0, 0, 90)).rotate(new Vec3(1, 0, 0)), EPS_F,
            "roll is right-handed about +Z");
    }

    @Test
    void eulerAngleRoundTrip() {
        // fromEulerAngle builds Z·Y·X in exactly the order getEulerAnglesZYX decomposes,
        // and toEulerAngle un-negates the yaw — round trip within float precision for a
        // gimbal-safe angle triple.
        Vec3 euler = new Vec3(20, -35, 40);
        Vec3 back = DQuaternion.fromEulerAngle(euler).toEulerAngle();
        assertVec(euler, back, 1e-4, "euler round trip (pitch, yaw, roll degrees)");
    }

    // ------------------------------------------------------------------------ JOML bridge

    @Test
    void mcQuaternionBridgeCopiesComponents() {
        DQuaternion q = new DQuaternion(0.5, -0.5, 0.5, 0.5);
        org.joml.Quaternionf mc = q.toMcQuaternion();
        assertEquals(0.5f, mc.x, 0, "x");
        assertEquals(-0.5f, mc.y, 0, "y");
        assertEquals(0.5f, mc.z, 0, "z");
        assertEquals(0.5f, mc.w, 0, "w");

        DQuaternion fromDouble = DQuaternion.fromMcQuaternion(
            new org.joml.Quaterniond(0.1, 0.2, 0.3, 0.9));
        assertQuatComponents(0.1, 0.2, 0.3, 0.9, fromDouble, 0, "Quaterniond copies exactly");
    }
