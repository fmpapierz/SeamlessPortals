    private static final double EPS = 1e-12;
    /** For values that pass through a float (Quaternionf/Matrix4f) round trip. */
    private static final double EPS_F = 1e-5;

    private static final double SIN45 = 0.7071067811865476; // sqrt(2)/2
    private static final double SIN22_5 = 0.3826834323650898;
    private static final double COS22_5 = 0.9238795325112867;

    private static void assertVec(Vec3 expected, Vec3 actual, double eps, String msg) {
        assertEquals(expected.x, actual.x, eps, msg + " (x); actual=" + actual);
        assertEquals(expected.y, actual.y, eps, msg + " (y); actual=" + actual);
        assertEquals(expected.z, actual.z, eps, msg + " (z); actual=" + actual);
    }

    /**
     * Double-cover-aware quaternion comparison implemented independently of the class
     * under test: q and -q represent the same rotation, so accept either sign.
     */
    private static void assertSameRotation(
        DQuaternion expected, DQuaternion actual, double eps, String msg
    ) {
        boolean plus = Math.abs(expected.x - actual.x) < eps
            && Math.abs(expected.y - actual.y) < eps
            && Math.abs(expected.z - actual.z) < eps
            && Math.abs(expected.w - actual.w) < eps;
        boolean minus = Math.abs(expected.x + actual.x) < eps
            && Math.abs(expected.y + actual.y) < eps
            && Math.abs(expected.z + actual.z) < eps
            && Math.abs(expected.w + actual.w) < eps;
        assertTrue(plus || minus,
            msg + " — expected ±" + expected + " but was " + actual);
    }

    private static void assertQuatComponents(
        double x, double y, double z, double w, DQuaternion actual, double eps, String msg
    ) {
        assertEquals(x, actual.x, eps, msg + " (x); actual=" + actual);
        assertEquals(y, actual.y, eps, msg + " (y); actual=" + actual);
        assertEquals(z, actual.z, eps, msg + " (z); actual=" + actual);
        assertEquals(w, actual.w, eps, msg + " (w); actual=" + actual);
    }

    // ---------------------------------------------------------------- rotation semantics

    @Test
    void rotateIsActiveRightHandedRotation() {
        // Right-hand rule about +Y by +90°: x̂ → -ẑ, ẑ → x̂, ŷ fixed.
        DQuaternion ry90 = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90);
        assertVec(new Vec3(0, 0, -1), ry90.rotate(new Vec3(1, 0, 0)), EPS,
            "+90° about +Y must map x̂ to -ẑ (active, right-handed)");
        assertVec(new Vec3(1, 0, 0), ry90.rotate(new Vec3(0, 0, 1)), EPS,
            "+90° about +Y must map ẑ to x̂");
        assertVec(new Vec3(0, 1, 0), ry90.rotate(new Vec3(0, 1, 0)), EPS,
            "the rotation axis is fixed");
    }

    @Test
    void rotationByDegreesNormalizesAxisAndMatchesHandComputedComponents() {
        // q = (axis*sin(θ/2), cos(θ/2)); for θ=90° about ŷ: (0, sin45°, 0, cos45°).
        DQuaternion q = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90);
        assertQuatComponents(0, SIN45, 0, SIN45, q, EPS, "axis-angle components (cos45°=sin45°)");

        // A non-normalized axis input must produce the identical quaternion.
        DQuaternion q2 = DQuaternion.rotationByDegrees(new Vec3(0, 17.5, 0), 90);
        assertQuatComponents(q.x, q.y, q.z, q.w, q2, EPS, "axis is normalized internally");
    }

    // ------------------------------------------------------- multiplication order convention

    @Test
    void hamiltonProductMatchesHandComputedComponents() {
        // q1 = 90° about X = (s,0,0,c); q2 = 90° about Y = (0,s,0,c) with s = c = sqrt(2)/2.
        // Hamilton product q1⊗q2 by the standard formula (hand-expanded):
        //   x = w1*x2 + x1*w2 + y1*z2 - z1*y2 = 0    + s*c  + 0 - 0 = 1/2
        //   y = w1*y2 - x1*z2 + y1*w2 + z1*x2 = c*s  - 0    + 0 + 0 = 1/2
        //   z = w1*z2 + x1*y2 - y1*x2 + z1*w2 = 0    + s*s  - 0 + 0 = 1/2
        //   w = w1*w2 - x1*x2 - y1*y2 - z1*z2 = c*c  - 0    - 0 - 0 = 1/2
        // (1/2,1/2,1/2,1/2) is the 120° rotation about (1,1,1)/sqrt(3), which cycles x̂→ŷ→ẑ→x̂.
        DQuaternion q1 = DQuaternion.rotationByDegrees(new Vec3(1, 0, 0), 90);
        DQuaternion q2 = DQuaternion.rotationByDegrees(new Vec3(0, 1, 0), 90);
        DQuaternion product = q1.hamiltonProduct(q2);
        assertQuatComponents(0.5, 0.5, 0.5, 0.5, product, EPS, "hand-expanded Hamilton product");
        assertVec(new Vec3(0, 1, 0), product.rotate(new Vec3(1, 0, 0)), EPS,
            "the 120° (1,1,1) rotation cycles x̂ to ŷ");
    }

    @Test
    void hamiltonProductAppliesRightOperandFirst() {
        // a = 90° about X (ŷ→ẑ), b = 90° about Z (x̂→ŷ). These do NOT commute on x̂:
        //   b first, then a: x̂ →(b)→ ŷ →(a)→ ẑ
        //   a first, then b: x̂ →(a)→ x̂ →(b)→ ŷ
        // IP convention (DQuaternion.hamiltonProduct javadoc): a.hamiltonProduct(b)
        // = "firstly do b's rotation and then do a's" — so it must map x̂ to ẑ.
        DQuaternion a = DQuaternion.rotationByDegrees(new Vec3(1, 0, 0), 90);
        DQuaternion b = DQuaternion.rotationByDegrees(new Vec3(0, 0, 1), 90);

        assertVec(new Vec3(0, 0, 1), a.hamiltonProduct(b).rotate(new Vec3(1, 0, 0)), EPS,
            "a.hamiltonProduct(b) applies b FIRST, a second");
        assertVec(new Vec3(0, 1, 0), b.hamiltonProduct(a).rotate(new Vec3(1, 0, 0)), EPS,
            "b.hamiltonProduct(a) applies a FIRST, b second (order matters)");
    }

    @Test
    void combineAppliesThisFirst() {
        // a.combine(b) = "firstly apply this (a) and then other (b)" = b⊗a:
        //   x̂ →(a: 90° about X)→ x̂ →(b: 90° about Z)→ ŷ
        DQuaternion a = DQuaternion.rotationByDegrees(new Vec3(1, 0, 0), 90);
        DQuaternion b = DQuaternion.rotationByDegrees(new Vec3(0, 0, 1), 90);
        assertVec(new Vec3(0, 1, 0), a.combine(b).rotate(new Vec3(1, 0, 0)), EPS,
            "a.combine(b) applies a FIRST, b second");
    }

